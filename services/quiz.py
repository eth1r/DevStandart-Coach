def check_answer(answer: str, question: QuizQuestion) -> bool:
    """Keyword-fallback: True если ответ содержит хотя бы одно ключевое слово."""
    normalized = answer.lower().strip()
    return any(kw.lower() in normalized for kw in question.keywords)
