from dataclasses import dataclass


@dataclass(frozen=True)
class QuizQuestion:
    text: str
    expected_answer: str        # для LLM-судьи: что должен выразить правильный ответ
    wrong_answer_hint: str      # короткая подсказка при неверном ответе
    keywords: tuple[str, ...]   # ключевые слова для keyword-fallback


